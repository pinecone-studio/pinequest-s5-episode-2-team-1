/**
 * Хими 7–11-ийн сурах бичгийн бүлэг, сэдвийн roadmap (номын агуулгаас).
 * Сэдэв урт тул ~6 хуудсаар хувааж, зангилаа бүрийг агуулгаар нь нэрлэсэн; бүлгийн «Өөрийгөө үнэлээрэй» нь сүүлийн сэдэвтээ.
 * Template байхгүй: зангилаа бүр номын хуудасны хүрээ (`ref`), хуудас = сан дахь хуудас.
 */
import type { MathRoadmapNode, MathRoadmapTopic } from './mathRoadmap';

/** [хичээлийн нэр, эхлэх хуудас, дуусах хуудас] — бүлгийн нүүр хуудсыг алгасдаг тул хүрээ тасралттай байж болно. */
type Lesson = readonly [title: string, from: number, to: number];

const topic = (slug: string, title: string, lessons: readonly Lesson[]): MathRoadmapTopic => ({
  title,
  nodes: lessons.map(([name, from, to]): MathRoadmapNode => ({ title: name, templateIds: [], ref: `${slug}:${from}-${to}` })),
});

