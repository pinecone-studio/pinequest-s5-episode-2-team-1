const advancedRoadmap = (grade: AdvancedMathGrade): readonly MathRoadmapTopic[] =>
  ADVANCED_MATH_CURRICULUM[grade].map((group) =>
    topic(
      group.title,
      group.lessons.map((item) => node(item.title, advancedMathTemplateId(item.ref))),
    ),
  );

