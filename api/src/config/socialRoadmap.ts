/**
 * Нийгэм судлал 7–11-ийн сурах бичгийн бүлэг, хичээлийн roadmap (номын «Агуулга» хуудаснаас).
 * Template байхгүй: зангилаа бүр номын хуудасны хүрээ (`ref`), асуултыг тэр хуудсаар үүсгэж DB-д хадгална.
 * Эдгээр номд хэвлэмэл хуудас = сан дахь хуудас (page_offset 0). «Бүлгийн дүгнэлт» хуудсууд зангилаа болохгүй.
 */
import type { MathRoadmapNode, MathRoadmapTopic } from './mathRoadmap';

/** [хичээлийн нэр, эхлэх хуудас] */
type Lesson = readonly [title: string, from: number];

/** Хичээл бүр дараагийн хичээлийн өмнөх хуудас хүртэл; бүлгийн сүүлийнх нь `last` хуудас хүртэл. */
const topic = (slug: string, title: string, last: number, lessons: readonly Lesson[]): MathRoadmapTopic => ({
  title,
  nodes: lessons.map(([name, from], i): MathRoadmapNode => {
    const to = i + 1 < lessons.length ? lessons[i + 1][1] - 1 : last;
    return { title: name, templateIds: [], ref: `${slug}:${from}-${to}` };
  }),
});

