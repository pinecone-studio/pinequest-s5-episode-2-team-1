/** Үсгийн өргөн, үсэг хоорондын зай (бүдүүрүүлсний дараа 1 үлдэнэ), нийт мөр (дээд тэмдэг + 7 + доод сүүл) — pixel-ээр. */
export const GLYPH_W = 5;
export const GLYPH_GAP = 2;
export const GLYPH_ROWS = 9;

/**
 * Текстийн бүх асаалттай pixel-ийг [x, y] хэлбэрээр (y=0 нь дээд тэмдгийн мөр). Pixel бүрийг баруун тийш нэг давхарлаж
 * бүдүүн (bold) болгоно. Танихгүй тэмдэгтийг алгасна.
 */
export function pixelsOf(text: string): { cells: [number, number][]; width: number } {
  const cells: [number, number][] = [];
  let ox = 0;
  for (const c of text.toUpperCase()) {
    const glyph = GLYPHS[c];
    if (!glyph) continue;
    const lines = [glyph.top ?? '', ...glyph.rows, glyph.bottom ?? ''];
    lines.forEach((line, y) =>
      [...line].forEach((p, x) => {
        if (p !== '#') return;
        if (glyph.raw || line[x - 1] !== '#') cells.push([ox + x, y]);
        // нэг pixel-ийн завсрыг (Ш, Ж) хаавал үсэг бөөн болно
        if (!glyph.raw && (line[x + 1] === '#' || line[x + 2] !== '#')) cells.push([ox + x + 1, y]);
      }),
    );
    ox += (glyph.raw ? glyph.rows[0].length : GLYPH_W + 1) + GLYPH_GAP - 1;
  }
  return { cells, width: Math.max(0, ox - GLYPH_GAP + 1) };
}
